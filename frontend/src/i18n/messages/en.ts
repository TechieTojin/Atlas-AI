export type PluralForms = Partial<Record<Intl.LDMLPluralRule, string>> & { other: string }

export interface MessageTree {
  [key: string]: string | PluralForms | MessageTree
}

type Join<Prefix extends string, Key extends string> = Prefix extends '' ? Key : `${Prefix}.${Key}`

/** Dotted paths to every leaf message (strings and plural objects). */
export type MessageKey<T = typeof en, Prefix extends string = ''> = {
  [K in keyof T & string]: T[K] extends string
    ? Join<Prefix, K>
    : T[K] extends { other: string }
      ? Join<Prefix, K>
      : MessageKey<T[K], Join<Prefix, K>>
}[keyof T & string]

/** Non-English dictionaries: same shape, any subset of keys, any plural categories. */
export type PartialMessages<T = typeof en> = {
  [K in keyof T]?: T[K] extends string
    ? string
    : T[K] extends { other: string }
      ? PluralForms
      : PartialMessages<T[K]>
}
